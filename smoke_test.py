"""
SpaceGuard AI — Smoke Test (manual end-to-end check)

WHAT IT COVERS
--------------
A quick end-to-end exercise of the core "spacecraft health" pipeline:

    1. Load the ISS-Alpha mission from the database.
    2. Grab its most recent telemetry record.
    3. Run the full AI analysis pipeline on that record:
       health score -> anomaly detection -> watsonx explanation ->
       trend predictions.
    4. Print every part of the result in a human-readable report.
    5. Show database counts for Alert and AIAnalysis rows, so you can
       confirm the pipeline actually wrote its outputs.

This is a *smoke test*, not an automated test suite: it talks to real
models and (if configured) the real watsonx API, and prints results to
the console instead of asserting. Run it after seeding demo data to verify
the whole stack works together.

HOW TO RUN (from the project root):

    python manage.py shell < smoke_test.py      # or simply:
    python smoke_test.py

(Requires the demo data to exist — e.g. load the seed fixtures first —
because it looks up the mission named 'ISS-Alpha'.)
"""
import sys, os, django

# Make `backend/` importable, since the Django apps (missions, ai, ...) live
# in there and this script sits in the project root.
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'backend'))
# Tell Django which settings to use, then bootstrap it so models are usable
# outside of `manage.py` (this is what a standalone script must do).
os.environ['DJANGO_SETTINGS_MODULE'] = 'spaceguard.settings'
django.setup()
# Import necessary models and functions
from missions.models import Mission
from ai.pipeline import run_analysis_pipeline

# --- Section 1: pick the input data --------------------------------------
# The demo mission and its newest telemetry reading become the pipeline's input.
m = Mission.objects.get(spacecraft_name='ISS-Alpha')
t = m.telemetry_records.order_by('-timestamp').first()
result = run_analysis_pipeline(t)

# --- Section 2: unpack the pipeline result --------------------------------
# The pipeline returns one dict with all four analysis outputs.
health = result['health']
anomaly = result['anomaly']
explanation = result['explanation']
predictions = result['predictions']

# --- Section 3: print the health score report ------------------------------
print('=== SPACEGUARD AI ANALYSIS RESULT ===')
print(f'Health Score : {health["health_score"]}/100')
print(f'Risk Level   : {health["risk_level"]}')
print(f'Category     : {health["health_category"]}')
print(f'Score Breakdown: {health["score_breakdown"]}')
print()
# --- Section 4: print the anomaly detection report -------------------------
print(f'Anomaly      : {anomaly["is_anomaly"]}')
print(f'Severity     : {anomaly["severity"]}')
print(f'Subsystem    : {anomaly["affected_subsystem"]}')
print(f'Score        : {anomaly["anomaly_score"]}')
print(f'Suspicious   : {anomaly["suspicious_parameters"]}')
print()
# --- Section 5: print the AI (watsonx) explanation --------------------------
print(f'Generated by : {explanation["generated_by"]}')
print(f'Problem      : {str(explanation["detected_problem"])[:100]}')
print(f'Action       : {str(explanation["recommended_action"])[:100]}')
print()
# --- Section 6: print trend predictions (and any threshold warnings) -------
for p in predictions[:3]:
    w = p.get('warning_message', '')
    if w:
        print(f'WARNING: {w[:100]}')
    else:
        print(f'Trend [{p["parameter"]}]: {p["trend_direction"]} -> {p["predicted_value"]}')

# --- Section 7: verify pipeline side effects in the database ---------------
# The pipeline should have persisted its outputs: an Alert row (if the
# anomaly was alert-worthy) and an AIAnalysis row. If these counts are 0
# when they shouldn't be, persistence is broken even though analysis ran.
from alerts.models import Alert
print()
print(f'Total Alerts : {Alert.objects.count()}')
from anomaly.models import AIAnalysis
print(f'AI Analyses  : {AIAnalysis.objects.count()}')
